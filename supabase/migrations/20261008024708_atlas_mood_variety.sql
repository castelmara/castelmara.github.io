create index if not exists daily_randoms_date_phrase_idx
  on public.daily_randoms (random_date, phrase_id);

create or replace function public.get_today_random()
returns table(phrase_id uuid, phrase text)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_date date := (now() at time zone 'Europe/Madrid')::date;
  v_phrase uuid;
begin
  if v_uid is null then
    raise exception 'Сначала войдите в аккаунт';
  end if;

  select d.phrase_id into v_phrase
  from public.daily_randoms d
  where d.user_id = v_uid and d.random_date = v_date;

  if v_phrase is null then
    -- Serialize new draws for this day, including two devices of one account.
    perform pg_catalog.pg_advisory_xact_lock(1096043603, v_date - date '2000-01-01');
    select d.phrase_id into v_phrase
    from public.daily_randoms d
    where d.user_id = v_uid and d.random_date = v_date;

    if v_phrase is null then
      with candidates as (
        select p.id,
          exists (
            select 1 from public.daily_randoms history
            where history.user_id = v_uid
              and history.random_date >= v_date - 30
              and history.random_date < v_date
              and history.phrase_id = p.id
          ) as recent,
          (select count(*) from public.daily_randoms today
           where today.random_date = v_date and today.phrase_id = p.id) as uses_today
        from public.daily_phrases p
        where p.active and btrim(p.explanation) <> ''
      )
      select c.id into v_phrase from candidates c
      -- Avoid personal repeats first, then draw from the least-used daily pool.
      -- If every candidate is recent, this also provides a safe small-pool fallback.
      order by c.recent, c.uses_today, random()
      limit 1;

      if v_phrase is null then
        select p.id into v_phrase from public.daily_phrases p
        where p.active order by random() limit 1;
      end if;
      if v_phrase is null then
        raise exception 'Список настроений пока пуст';
      end if;

      insert into public.daily_randoms(user_id, random_date, phrase_id)
      values (v_uid, v_date, v_phrase)
      on conflict do nothing;
      select d.phrase_id into v_phrase
      from public.daily_randoms d
      where d.user_id = v_uid and d.random_date = v_date;
    end if;
  end if;

  return query
  select p.id, p.phrase from public.daily_phrases p where p.id = v_phrase;
end;
$function$;

revoke execute on function public.get_today_random() from public, anon;
grant execute on function public.get_today_random() to authenticated;
