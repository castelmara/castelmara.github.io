begin;
set local role authenticated;
do $test$
declare actor uuid; other_actor uuid; reviewer uuid; owned text; foreign_id text; first_id uuid; next_id uuid; path text; blocked boolean;
begin
 select co.user_id,co.character_id into actor,owned from public.character_owners co join public.profiles p on p.id=co.user_id and p.role='player' join public.atlas_character_catalog c on c.id=co.character_id and c.active limit 1;
 select id into other_actor from public.profiles where id<>actor and role='player' limit 1;
 select id into reviewer from public.profiles where nickname='passion' and role='superadmin';
 assert actor is not null and reviewer is not null and other_actor is not null;
 select id into foreign_id from public.atlas_character_catalog where active and id<>owned and not exists(select 1 from public.character_owners where user_id=actor and character_id=atlas_character_catalog.id) limit 1;
 perform set_config('request.jwt.claim.sub',actor::text,true);
 path:=actor::text||'/review-test.pdf';
 insert into storage.objects(bucket_id,name,metadata) values('atlas-questionnaires',path,'{"mimetype":"application/pdf"}');
 insert into public.atlas_questionnaire_submissions(character_id,actor_id,content,file_path,file_name) values(owned,actor,'{"fullName":"Test character","faculty":"Sport","faceclaim":"Test face"}',path,'test.pdf') returning id into first_id;
 assert not exists(select 1 from public.atlas_questionnaire_publications where submission_id=first_id),'Pending hidden from publication';
 blocked:=false;
 begin insert into public.atlas_questionnaire_submissions(character_id,actor_id,content,file_path) values(owned,actor,'{"fullName":"Test","faculty":"Sport","faceclaim":"Test face"}',path); exception when unique_violation then blocked:=true;end;
 assert blocked,'Duplicate pending rejected';
 blocked:=false;
 begin insert into public.atlas_questionnaire_submissions(character_id,actor_id,content,file_path) values(foreign_id,actor,'{"fullName":"Test","faculty":"Sport","faceclaim":"Test face"}',path); exception when insufficient_privilege then blocked:=true;end;
 assert blocked,'Foreign character rejected';
 blocked:=false;
 begin perform public.atlas_review_questionnaire(first_id,'approved',''); exception when others then blocked:=true;end;
 assert blocked,'Player cannot approve';
 blocked:=false;
 begin perform public.atlas_save_questionnaire_text(first_id,'forged',0);exception when others then blocked:=true;end;
 assert blocked,'Player cannot edit administrative text';
 blocked:=false;
 begin update public.atlas_questionnaire_submissions set status='approved' where id=first_id; exception when insufficient_privilege then blocked:=true;end;
 assert blocked,'Player cannot change status directly';
 perform set_config('request.jwt.claim.sub',other_actor::text,true);
 assert not exists(select 1 from public.atlas_questionnaire_submissions where id=first_id),'Private request';
 assert not exists(select 1 from storage.objects where bucket_id='atlas-questionnaires' and name=path),'Private attachment';
 perform set_config('request.jwt.claim.sub',reviewer::text,true);
 assert exists(select 1 from public.atlas_questionnaire_submissions where id=first_id);
 assert exists(select 1 from storage.objects where bucket_id='atlas-questionnaires' and name=path);
 assert public.atlas_save_questionnaire_text(first_id,'Редакция суперадмина',0)=1;
 blocked:=false;
 begin perform public.atlas_save_questionnaire_text(first_id,'stale overwrite',0); exception when others then blocked:=true;end;
 assert blocked,'Concurrent editor rejected';
 perform public.atlas_decide_questionnaire(first_id,'approved','','Редакция для публикации',1);
 assert exists(select 1 from public.atlas_questionnaire_publications where submission_id=first_id and document_text='Редакция для публикации');
 assert exists(select 1 from public.atlas_questionnaire_submissions where id=first_id and review_note like '%успешно зарегистрирован%');
 assert exists(select 1 from public.atlas_questionnaire_publications where submission_id=first_id);
 blocked:=false;
 begin perform public.atlas_review_questionnaire(first_id,'rejected','late'); exception when others then blocked:=true;end;
 assert blocked,'Decision immutable';
 perform set_config('request.jwt.claim.sub',actor::text,true);
 insert into public.atlas_questionnaire_submissions(character_id,actor_id,content,file_path) values(owned,actor,'{"fullName":"Test","faculty":"Sport","faceclaim":"Test face"}',path) returning id into next_id;
 perform set_config('request.jwt.claim.sub',reviewer::text,true);
 perform public.atlas_review_questionnaire(next_id,'rejected','Исправить биографию');
 assert exists(select 1 from public.atlas_questionnaire_publications where submission_id=first_id),'Rejection preserves published version';
 perform set_config('request.jwt.claim.sub',actor::text,true);
 insert into public.atlas_questionnaire_submissions(character_id,actor_id,content,file_path) values(owned,actor,'{"fullName":"Test","faculty":"Sport","faceclaim":"Test face"}',path) returning id into next_id;
 perform set_config('request.jwt.claim.sub',reviewer::text,true);
 perform public.atlas_review_questionnaire(next_id,'approved','');
 assert exists(select 1 from public.atlas_questionnaire_publications where submission_id=next_id);
 assert exists(select 1 from public.atlas_questionnaire_submissions where id=first_id and status='approved'),'Previous version retained';
end $test$;
rollback;
select 'questionnaire ownership, private files, review, history and passion permissions passed; rolled back' as result;
