begin;
set local role authenticated;
do $test$
declare a uuid;b uuid;outsider uuid;admin_id uuid;owned text;dm uuid;grp uuid;general uuid;msg uuid;topic uuid;blocked boolean;path text;
begin
 select p.id,co.character_id into a,owned from public.profiles p join public.character_owners co on co.user_id=p.id join public.atlas_character_catalog c on c.id=co.character_id where p.role='player' and c.active limit 1;
 select id into b from public.profiles where role='player' and id<>a limit 1;
 select id into outsider from public.profiles where role='player' and id not in(a,b) limit 1;
 select id into admin_id from public.profiles where role='superadmin' limit 1;
 assert a is not null and b is not null and outsider is not null and admin_id is not null;
 perform set_config('request.jwt.claim.sub',a::text,true);
 select id into general from public.atlas_player_rooms where kind='general';
 assert general is not null;
 dm:=public.atlas_create_player_room('dm','',array[b]);
 assert public.atlas_create_player_room('dm','',array[b])=dm,'DM must be reused';
 grp:=public.atlas_create_player_room('group','Test group',array[b]);
 insert into public.atlas_player_messages(room_id,sender_id,body) values(dm,a,'Private CAPS') returning id into msg;
 insert into public.atlas_player_messages(room_id,sender_id,body) values(general,a,'General test');
 path:=a::text||'/'||dm::text||'/test.jpg';
 insert into storage.objects(bucket_id,name,metadata) values('atlas-player-chat',path,'{"mimetype":"image/jpeg"}');
 insert into public.atlas_player_messages(room_id,sender_id,images) values(dm,a,array[path]);
 blocked:=false;
 begin insert into public.atlas_player_messages(room_id,sender_id,images) values(grp,a,array[path]);exception when others then blocked:=true;end;
 assert blocked,'Photo cannot be copied into another room';
 blocked:=false;
 begin insert into public.atlas_player_messages(room_id,sender_id,body) values(dm,b,'impersonation');exception when others then blocked:=true;end;
 assert blocked,'Cannot impersonate another player';
 blocked:=false;
 begin insert into public.atlas_player_room_members(room_id,user_id) values(dm,outsider);exception when others then blocked:=true;end;
 assert blocked,'Cannot add arbitrary members directly';
 insert into public.atlas_social_entries(kind,actor_id,author_kind,character_id,title,body) values('topic',a,'character',owned,'Character topic','') returning id into topic;
 insert into public.atlas_social_entries(kind,parent_id,actor_id,author_kind,character_id,body) values('reply',topic,a,'character',owned,'Roleplay');
 perform set_config('request.jwt.claim.sub',b::text,true);
 assert (select body='Private CAPS' from public.atlas_player_messages where id=msg),'Recipient can read';
 assert exists(select 1 from storage.objects where bucket_id='atlas-player-chat' and name=path),'Recipient can read photo';
 assert public.atlas_create_player_room('dm','',array[a])=dm,'Reverse pair must reuse DM';
 insert into public.atlas_player_messages(room_id,sender_id,body) values(dm,b,'Recipient reply');
 update public.atlas_player_messages set body='bad' where id=msg;
 assert not found,'Cannot edit someone else';
 perform set_config('request.jwt.claim.sub',outsider::text,true);
 assert not exists(select 1 from public.atlas_player_rooms where id in(dm,grp)),'Outsider cannot list rooms';
 assert not exists(select 1 from public.atlas_player_messages where id=msg),'Outsider cannot read messages';
 assert not exists(select 1 from public.atlas_player_room_members where room_id=dm),'Outsider cannot read members';
 assert not exists(select 1 from storage.objects where bucket_id='atlas-player-chat' and name=path),'Outsider cannot read private photo';
 blocked:=false;
 begin insert into public.atlas_player_messages(room_id,sender_id,body) values(dm,outsider,'injection');exception when others then blocked:=true;end;
 assert blocked,'Outsider cannot write';
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 assert not exists(select 1 from public.atlas_player_messages where id=msg),'Staff cannot read private conversations they have not joined';
 insert into public.atlas_social_entries(kind,actor_id,author_kind,title,body) values('topic',admin_id,'atlas','Admin topic','');
end $test$;
rollback;
