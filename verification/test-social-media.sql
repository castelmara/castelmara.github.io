begin;
set local role authenticated;
do $test$
declare a uuid;b uuid;outsider uuid;owned text;dm uuid;grp uuid;msg uuid;older uuid;post uuid;reply uuid;blocked boolean;path text;stamp timestamptz;
begin
 select p.id,co.character_id into a,owned from public.profiles p join public.character_owners co on co.user_id=p.id join public.atlas_character_catalog c on c.id=co.character_id where p.role='player' and c.active limit 1;
 select id into b from public.profiles where role='player' and id<>a limit 1;
 select id into outsider from public.profiles where role='player' and id not in(a,b) limit 1;
 perform set_config('request.jwt.claim.sub',a::text,true);
 dm:=public.atlas_create_player_room('dm','',array[b]);
 grp:=public.atlas_create_player_room('group','Temporary test',array[b]);
 insert into public.atlas_player_messages(room_id,sender_id,body) values(dm,a,'First') returning id into older;
 path:=a::text||'/'||dm::text||'/'||gen_random_uuid()||'.webm';
 insert into storage.objects(bucket_id,name,metadata) values('atlas-player-chat',path,'{"mimetype":"audio/webm"}');
 insert into public.atlas_player_messages(room_id,sender_id,audio_path,audio_seconds) values(dm,a,path,3) returning id,created_at into msg,stamp;
 blocked:=false;begin insert into public.atlas_player_messages(room_id,sender_id,audio_path,audio_seconds) values(grp,a,path,3);exception when others then blocked:=true;end;
 assert blocked,'Cannot attach audio from another room';
 blocked:=false;begin insert into public.atlas_player_reads values(dm,b,now());exception when others then blocked:=true;end;
 assert blocked,'Cannot forge read receipts directly';
 insert into public.atlas_social_entries(kind,actor_id,author_kind,character_id,body,story_at) values('feed',a,'character',owned,'Post','2024-10-10 17:30') returning id into post;
 insert into public.atlas_social_entries(kind,parent_id,actor_id,author_kind,character_id,body) values('reply',post,a,'character',owned,'Comment') returning id into reply;
 blocked:=false;begin insert into public.atlas_social_entries(kind,parent_id,actor_id,author_kind,character_id,body) values('reply',reply,a,'character',owned,'Nested injection');exception when others then blocked:=true;end;
 assert blocked,'Comments must target a post/topic';
 update public.atlas_social_entries set story_at='2024-09-03 12:00' where id=post;
 assert (select story_at='2024-09-03 12:00' and created_at>='2026-01-01' from public.atlas_social_entries where id=post),'Roleplay date separate from server timestamp';
 perform set_config('request.jwt.claim.sub',b::text,true);
 assert exists(select 1 from storage.objects where name=path),'Recipient can access audio';
 perform public.atlas_mark_player_read(dm,msg);
 assert (select read_at=stamp from public.atlas_player_reads where room_id=dm and user_id=b),'Read saved for actual message';
 perform public.atlas_mark_player_read(dm,older);
 assert (select read_at=stamp from public.atlas_player_reads where room_id=dm and user_id=b),'Read cursor cannot regress';
 blocked:=false;begin insert into public.atlas_player_messages(room_id,sender_id,audio_path,audio_seconds) values(dm,b,path,3);exception when others then blocked:=true;end;
 assert blocked,'Cannot attach another sender audio';
 perform set_config('request.jwt.claim.sub',outsider::text,true);
 assert not exists(select 1 from storage.objects where name=path),'Outsider cannot access audio';
 assert not exists(select 1 from public.atlas_player_reads where room_id=dm),'Outsider cannot inspect read receipts';
 blocked:=false;begin perform public.atlas_mark_player_read(dm,msg);exception when others then blocked:=true;end;
 assert blocked,'Outsider cannot mark private chat read';
end $test$;
rollback;
